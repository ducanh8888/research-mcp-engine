async def test_elicit_completed_report_downloads_papers_never_narrative(context):
    def handler(request):
        if request.url.host == "elicit.com":
            return httpx.Response(200, json={"status": "completed", "risUrl": EXPORT_URL,
                "exportsStatus": "ready", "result": {"reportBody": "Generated findings", "summary": "Generated"}})
        assert "authorization" not in request.headers
        return httpx.Response(200, text="TY  - JOUR\nTI  - Source paper\nDO  - 10.1234/ABC\nAU  - An Author\nPY  - 2021\nAB  - Original abstract\nER  -\n")

    ctx = context("elicit_api", handler=handler)
    # A new provider instance has no in-memory state from the job creation process.
    update = await ElicitAPIProvider().poll(ctx, job_ref())
    assert update.status == "completed" and update.result.document is None
    assert ctx.validated == [EXPORT_URL]
    hit = update.result.hits[0]
    assert hit.ids == {"doi": "10.1234/abc"} and hit.snippet == "Original abstract"
    assert hit.raw["session_id"] == SESSION_ID and hit.rank == 1
    assert "Generated findings" not in update.result.model_dump_json()


