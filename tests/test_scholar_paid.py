class Context:
    def __init__(self, provider, handler, *, credentials=None, options=None):
        self.provider = provider
        self.account_id = 7
        self.credentials = {"api_key": "fixture-key"} if credentials is None else credentials
        self.options = options or {}
        self.requests = []
        self.validated = []

        def capture(request):
            self.requests.append(request)
            return handler(request)

        self.client = httpx.AsyncClient(transport=httpx.MockTransport(capture))

    async def request(self, method, url, **kwargs):
        return await self.client.request(method, url, **kwargs)

    async def validate_url(self, url):
        self.validated.append(url)
        parsed = urlsplit(url)
        if parsed.scheme != "https" or parsed.hostname in {"localhost", "127.0.0.1", "169.254.169.254"}:
            raise ProviderError(ErrorKind.BAD_REQUEST, "Unsafe export URL")


